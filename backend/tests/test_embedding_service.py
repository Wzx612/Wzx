"""Tests for EmbeddingService.

The BGE model is loaded once (module scope) and injected directly into the
class variable so all async tests reuse it without repeated 70s disk loads.
No mocks — every embedding is generated by the real model.
"""

import math
import time

import pytest
from sentence_transformers import SentenceTransformer

from app.services.embedding_service import EmbeddingService, _vec_literal

MODEL_NAME = EmbeddingService.MODEL_NAME
DIM = EmbeddingService.EMBEDDING_DIM


# ── Fixtures ──────────────────────────────────────────────────────────────────


@pytest.fixture(scope="module")
def bge_model() -> SentenceTransformer:
    """Load BGE model once for this test module and inject into service.

    Clears the reference on teardown so downstream test modules don't inherit
    the ~1.3 GB model allocation.
    """
    import gc

    model = SentenceTransformer(MODEL_NAME)
    EmbeddingService._model = model
    yield model
    EmbeddingService._model = None
    del model
    gc.collect()


# ── Helper ────────────────────────────────────────────────────────────────────


def cosine_similarity(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    mag_a = math.sqrt(sum(x * x for x in a))
    mag_b = math.sqrt(sum(y * y for y in b))
    if mag_a == 0 or mag_b == 0:
        return 0.0
    return dot / (mag_a * mag_b)


# ── Single embedding ──────────────────────────────────────────────────────────


class TestSingleEmbedding:
    async def test_dimension(self, bge_model):
        emb = await EmbeddingService.generate_embedding("测试文本")
        assert len(emb) == DIM

    async def test_returns_floats(self, bge_model):
        emb = await EmbeddingService.generate_embedding("real estate market")
        assert all(isinstance(v, float) for v in emb)

    async def test_normalized_unit_vector(self, bge_model):
        emb = await EmbeddingService.generate_embedding("北京房地产市场报告")
